static int sc2336p_fsync(struct v4l2_subdev *sd, bool slave)
{
	if (fsync_mode != 3)
		return 0;
	return smartsens_write_reg(sd, slave ? 0x3224 : 0x322f,
				   slave ? 0x83 : 0xa0);
}

