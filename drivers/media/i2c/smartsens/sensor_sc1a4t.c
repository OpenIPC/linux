/* Secondary sensor frame-sync half-frame offset. */
#define SC1A4TS1_SYNC_ROWS	1629

static int sc1a4t_set_vblank(struct v4l2_subdev *sd, s32 val)
{
	struct smartsens_sensor *sensor = to_smartsens_sensor(sd);
	u32 vts = sensor->height + val;
	s32 delay;
	int ret;

	ret = smartsens_set_vblank(sd, val);
	if (ret || !sensor->frame_sync_slave)
		return ret;

	delay = ((s32)(vts / 2) - SC1A4TS1_SYNC_ROWS) % (s32)vts;
	if (delay < 0)
		delay += vts;
	ret = smartsens_write_reg(sd, 0x3230, delay >> 8);
	if (ret)
		return ret;
	return smartsens_write_reg(sd, 0x3231, delay & 0xff);
}

static int sc1a4t_fsync(struct v4l2_subdev *sd, bool slave)
{
	int ret;

	if (fsync_mode != 3)
		return 0;
	if (slave)
		return smartsens_write_reg(sd, 0x3224, 0x97);
	ret = smartsens_write_reg(sd, 0x322e, 6);
	if (ret)
		return ret;
	return smartsens_write_reg(sd, 0x322f, 0x60);
}

