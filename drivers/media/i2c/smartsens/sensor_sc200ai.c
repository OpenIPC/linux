static int sc200ai_probe(struct i2c_client *client)
{
	struct device *dev = &client->dev;
	struct v4l2_fwnode_endpoint bus_cfg = {
		.bus_type = V4L2_MBUS_CSI2_DPHY,
	};
	struct fwnode_handle *ep;
	struct smartsens_desc *desc;
	bool use_25fps = false;
	bool matched = false;
	unsigned int i;
	int ret;

	ep = fwnode_graph_get_next_endpoint(dev_fwnode(dev), NULL);
	if (!ep)
		return -ENOTCONN;

	ret = v4l2_fwnode_endpoint_alloc_parse(ep, &bus_cfg);
	fwnode_handle_put(ep);
	if (ret) {
		v4l2_fwnode_endpoint_free(&bus_cfg);
		return ret;
	}

	for (i = 0; i < bus_cfg.nr_of_link_frequencies; i++) {
		if (bus_cfg.link_frequencies[i] == sc200ai_link_freq_25fps[0]) {
			use_25fps = true;
			matched = true;
			break;
		}
		if (bus_cfg.link_frequencies[i] == sc200ai_link_freqs[0]) {
			matched = true;
			break;
		}
	}
	v4l2_fwnode_endpoint_free(&bus_cfg);
	if (!matched)
		return dev_err_probe(dev, -EINVAL,
				     "no supported link frequency found\n");

	if (!use_25fps)
		return smartsens_probe(client, &sc200ai_desc, false);

	desc = devm_kmemdup(dev, &sc200ai_desc, sizeof(*desc), GFP_KERNEL);
	if (!desc)
		return -ENOMEM;
	desc->primary_seqs = sc200ai_seqs_25fps;
	desc->link_freqs = sc200ai_link_freq_25fps;
	desc->pixel_rate = 74250000;
	desc->fps = 25;
	desc->vts_def = 1350;
	desc->exposure_max = desc->vts_def - desc->exposure_margin;
	desc->exposure_def = desc->exposure_max;
	desc->vblank_min = desc->vts_def - desc->height;
	desc->vblank_def = desc->vblank_min;
	desc->vblank_max = 6750 - desc->height;

	return smartsens_probe(client, desc, false);
}

