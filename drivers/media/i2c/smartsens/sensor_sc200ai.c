static int sc200ai_write_gain(struct v4l2_subdev *sd, u32 code)
{
	int ret;

	ret = smartsens_write_reg(sd, 0x3e09, code & 0xff);
	if (ret)
		return ret;
	ret = smartsens_write_reg(sd, 0x3e08, code >> 8);
	if (ret)
		return ret;
	if (code >= 0x3f47)
		return smartsens_write_reg(sd, 0x5799, 0x07);
	if (code <= 0x2f5f)
		return smartsens_write_reg(sd, 0x5799, 0x00);
	return 0;
}

