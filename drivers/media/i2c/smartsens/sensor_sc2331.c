static int sc2331_write_gain(struct v4l2_subdev *sd, u32 code)
{
	int ret;

	ret = smartsens_write_reg(sd, 0x3e08, code >> 8);
	if (ret)
		return ret;
	ret = smartsens_write_reg(sd, 0x3e07, code & 0xff);
	if (ret)
		return ret;
	return 0;
}

