static int jx_detect(struct device *dev, struct regmap *map, u16 expected)
{
	u64 hi, lo;
	int ret = 0;
	u16 id;

	cci_read(map, CCI_REG8(0x0a), &hi, &ret);
	cci_read(map, CCI_REG8(0x0b), &lo, &ret);
	if (ret)
		return ret;
	id = (hi << 8) | lo;
	if (id != expected) {
		dev_err(dev, "chip ID mismatch: got 0x%04x, expected 0x%04x\n",
			id, expected);
		return -ENODEV;
	}
	return 0;
}

static int jxf23_detect(struct device *dev, struct regmap *map)
{
	return jx_detect(dev, map, 0x0f23);
}

static int jxf37pa_detect(struct device *dev, struct regmap *map)
{
	return jx_detect(dev, map, 0x0841);
}

static int jxf38p_detect(struct device *dev, struct regmap *map)
{
	return jx_detect(dev, map, 0x0844);
}

static int jxh63p_detect(struct device *dev, struct regmap *map)
{
	return jx_detect(dev, map, 0x0848);
}

static int jx_standby(struct regmap *map, bool enable)
{
	return regmap_update_bits(map, 0x12, BIT(6), enable ? BIT(6) : 0);
}

static int jx_set_ctrl(struct regmap *map, u32 id, u32 value)
{
	int ret = 0;

	switch (id) {
	case V4L2_CID_EXPOSURE:
		cci_write(map, CCI_REG8(0x01), value & 0xff, &ret);
		cci_write(map, CCI_REG8(0x02), value >> 8, &ret);
		break;
	case V4L2_CID_VBLANK:
		cci_write(map, CCI_REG8(0x22), value & 0xff, &ret);
		cci_write(map, CCI_REG8(0x23), value >> 8, &ret);
		break;
	case V4L2_CID_ANALOGUE_GAIN:
		return regmap_write(map, 0x00, value);
	case V4L2_CID_HFLIP:
		return regmap_update_bits(map, 0x12, BIT(5),
					  value ? BIT(5) : 0);
	case V4L2_CID_VFLIP:
		return regmap_update_bits(map, 0x12, BIT(4),
					  value ? BIT(4) : 0);
	default:
		return -EINVAL;
	}
	return ret;
}

static int jxf23_set_ctrl(struct regmap *map, u32 id, u32 value)
{
	int ret = 0;

	if (id == V4L2_CID_ANALOGUE_GAIN) {
		if (value < 0x30) {
			cci_write(map, CCI_REG8(0x66), 0x04, &ret);
			cci_write(map, CCI_REG8(0x0c), 0x00, &ret);
		} else {
			cci_write(map, CCI_REG8(0x0c), 0x40, &ret);
			cci_write(map, CCI_REG8(0x66), 0x44, &ret);
		}
	}
	return ret ?: jx_set_ctrl(map, id, value);
}

