void helix_calc_qtable(u32 quality, u8 *qtable, u32 *qmem)
{
	u32 scale;
	unsigned int i;

	quality = clamp_t(u32, quality, 1, 100);
	scale = (quality < 50) ? (5000 / quality) : (200 - 2 * quality);

	for (i = 0; i < 64; i++) {
		u8 idx = helix_zigzag[i];
		u32 val = (helix_base_lum_qtable[idx] * scale + 50) / 100;
		qtable[i] = clamp_t(u32, val, 1, 255);
	}
	for (i = 0; i < 64; i++) {
		u8 idx = helix_zigzag[i];
		u32 val = (helix_base_chr_qtable[idx] * scale + 50) / 100;
		qtable[64 + i] = clamp_t(u32, val, 1, 255);
	}

	for (i = 0; i < 128; i++)
		qmem[i] = stock_qmem_lut[qtable[i]];
	for (i = 128; i < 256; i++)
		qmem[i] = 0;
}

static const u8 jpeg_header_jfif[20] = {
	0xFF, 0xD8,				/* SOI */
	0xFF, 0xE0, 0x00, 0x10,			/* APP0, len 16 */
	'J', 'F', 'I', 'F', 0x00,		/* identifier */
	0x01, 0x01,				/* version 1.1 */
	0x00,					/* density units */
	0x00, 0x01, 0x00, 0x01,			/* X/Y density (1x1) */
	0x00, 0x00,				/* thumbnail (0x0) */
};

static const u8 jpeg_sos_header[14] = {
	0xFF, 0xDA, 0x00, 0x0C,			/* SOS, len 12 */
	0x03,					/* 3 components */
	0x01, 0x00,				/* Y: DC 0, AC 0 */
	0x02, 0x11,				/* Cb: DC 1, AC 1 */
	0x03, 0x11,				/* Cr: DC 1, AC 1 */
	0x00, 0x3F, 0x00,			/* spectral selection: 0..63, AH/AL 0 */
};

static void jpeg_write_dqt(u8 **dst, u8 table_id, const u8 *qtable)
{
	u8 *p = *dst;

	*p++ = 0xFF;
	*p++ = 0xDB;
	put_unaligned_be16(67, p);
	p += 2;
	*p++ = table_id;
	memcpy(p, qtable, 64);
	p += 64;
	*dst = p;
}

static void jpeg_write_sof0(u8 **dst, u16 height, u16 width)
{
	static const u8 sof0_components[9] = {
		0x01, 0x22, 0x00,		/* Y:  2x2 sampling, DQT 0 */
		0x02, 0x11, 0x01,		/* Cb: 1x1 sampling, DQT 1 */
		0x03, 0x11, 0x01,		/* Cr: 1x1 sampling, DQT 1 */
	};
	u8 *p = *dst;

	*p++ = 0xFF;
	*p++ = 0xC0;
	put_unaligned_be16(2 + 1 + 2 + 2 + 1 + sizeof(sof0_components), p);
	p += 2;
	*p++ = 8;
	put_unaligned_be16(height, p);
	p += 2;
	put_unaligned_be16(width, p);
	p += 2;
	*p++ = 3;
	memcpy(p, sof0_components, sizeof(sof0_components));
	p += sizeof(sof0_components);
	*dst = p;
}

static void jpeg_write_dht(u8 **dst, u8 class_id, const u8 *bits, size_t nbits,
			   const u8 *vals, size_t nvals)
{
	u8 *p = *dst;

	*p++ = 0xFF;
	*p++ = 0xC4;
	put_unaligned_be16(2 + 1 + nbits + nvals, p);
	p += 2;
	*p++ = class_id;
	memcpy(p, bits, nbits);
	p += nbits;
	memcpy(p, vals, nvals);
	p += nvals;
	*dst = p;
}

size_t helix_jpeg_write_headers(u8 *buf, u32 width, u32 height,
				const u8 *qtable, u32 visible_width, u32 visible_height)
{
	const u8 *lum_q = qtable ? qtable : helix_qtable;
	const u8 *chr_q = qtable ? (qtable + 64) : (helix_qtable + 64);
	u32 vw = visible_width ? visible_width : width;
	u32 vh = visible_height ? visible_height : height;
	u8 *p = buf;

	memcpy(p, jpeg_header_jfif, sizeof(jpeg_header_jfif));
	p += sizeof(jpeg_header_jfif);

	jpeg_write_dqt(&p, 0, lum_q);
	jpeg_write_dqt(&p, 1, chr_q);

	jpeg_write_sof0(&p, (u16)vh, (u16)vw);

	jpeg_write_dht(&p, 0x00, dc_lum_bits, sizeof(dc_lum_bits),
		       dc_lum_vals, sizeof(dc_lum_vals));
	jpeg_write_dht(&p, 0x10, ac_lum_bits, sizeof(ac_lum_bits),
		       ac_lum_vals, sizeof(ac_lum_vals));
	jpeg_write_dht(&p, 0x01, dc_chr_bits, sizeof(dc_chr_bits),
		       dc_chr_vals, sizeof(dc_chr_vals));
	jpeg_write_dht(&p, 0x11, ac_chr_bits, sizeof(ac_chr_bits),
		       ac_chr_vals, sizeof(ac_chr_vals));

	memcpy(p, jpeg_sos_header, sizeof(jpeg_sos_header));
	p += sizeof(jpeg_sos_header);

	return (size_t)(p - buf);
}

void helix_jpeg_write_eoi(u8 *buf, size_t offset)
{
	buf[offset] = 0xFF;
	buf[offset + 1] = 0xD9;
}

int helix_jpeg_hw_start(struct helix_dev *hdev,
			dma_addr_t src_y_dma, dma_addr_t src_uv_dma,
			dma_addr_t dst_dma, u32 width, u32 height,
			u32 y_stride, u32 uv_stride, u32 fourcc,
			const u32 *qmem)
{
	struct helix_vdma_task task;
	const u32 *qm = qmem ? qmem : helix_qmem;
	u32 efe_ctrl;
	unsigned int i;

	if ((fourcc != V4L2_PIX_FMT_NV12 && fourcc != V4L2_PIX_FMT_NV21) ||
	    width & 15 || height & 15 ||
	    y_stride != width || uv_stride != width ||
	    (src_y_dma | src_uv_dma | dst_dma) & 127 ||
	    hdev->bounce_size != HELIX_BOUNCE_BUF_SIZE)
		return -EINVAL;

	efe_ctrl = (fourcc == V4L2_PIX_FMT_NV21) ? EFE_CTRL_NV21 : EFE_CTRL_NV12;

	helix_vdma_task_init(&task, hdev->task_vaddr, hdev->task_paddr,
			     HELIX_TASK_SIZE);

	helix_vdma_append(&task, REG_TCSM_FLUSH, 0);
	helix_vdma_append(&task, REG_JPGC_GLBI, JPGC_GLBI_INIT);

	for (i = 0; i < ARRAY_SIZE(helix_hufe_table); i++)
		helix_vdma_append(&task, REG_JPGC_HUFE + i * 4,
				  helix_hufe_table[i]);

	for (i = 0; i < 256; i++)
		helix_vdma_append(&task, REG_JPGC_QMEM + i * 4, qm[i]);

	helix_vdma_append(&task, REG_JPGC_STAT, 0);
	helix_vdma_append(&task, REG_JPGC_BSA, dst_dma);
	helix_vdma_append(&task, REG_JPGC_P0A, HELIX_INTERNAL_RAM);
	helix_vdma_append(&task, REG_JPGC_NMCU,
			  (width / 16) * (height / 16) - 1);
	helix_vdma_append(&task, REG_JPGC_NRSM, 0);
	helix_vdma_append(&task, REG_JPGC_P0C, JPGC_P0C_DEFAULT);
	helix_vdma_append(&task, REG_JPGC_P1C, JPGC_P1C_DEFAULT);
	helix_vdma_append(&task, REG_JPGC_P2C, JPGC_P2C_DEFAULT);
	helix_vdma_append(&task, REG_JPGC_MAX_BS, HELIX_BOUNCE_BUF_SIZE);
	helix_vdma_append(&task, REG_JPGC_GLBI, JPGC_GLBI_RUN);
	helix_vdma_append(&task, REG_JPGC_TRIG, JPGC_TRIG_ENCODE);

	helix_vdma_append(&task, REG_EFE_GEOM,
			  ((height / 16 - 1) << 16) | (width / 16 - 1));
	helix_vdma_append(&task, REG_EFE_RAWY_SBA, src_y_dma);
	helix_vdma_append(&task, REG_EFE_RAWC_SBA, src_uv_dma);
	helix_vdma_append(&task, REG_EFE_RAWV_SBA, 0);
	helix_vdma_append(&task, REG_EFE_RAW_STRD,
			  (y_stride << 16) | uv_stride);
	helix_vdma_append(&task, REG_EFE_RAW_DBA, HELIX_INTERNAL_RAM);
	helix_vdma_append(&task, REG_EFE_CTRL, efe_ctrl);

	helix_vdma_terminate(&task);

	return helix_vdma_kick(hdev, &task);
}
